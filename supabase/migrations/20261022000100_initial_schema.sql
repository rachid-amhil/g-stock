-- Schema for the private Gestion de stock API (Netlify Functions).
-- Only the server-side Supabase service role may access these tables.
-- Never expose the service role key in the browser.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  password_hash text not null,
  password_salt text not null,
  active boolean not null default true,
  last_login timestamptz,
  created_at timestamptz not null default now()
);
create unique index if not exists users_email_lower_uq on public.users (lower(email));

create table if not exists public.roles (
  id bigint generated by default as identity primary key,
  name text not null unique
);

create table if not exists public.permissions (
  id bigint generated by default as identity primary key,
  section text not null,
  action text not null,
  unique (section, action)
);

create table if not exists public.user_roles (
  user_id bigint not null references public.users(id) on delete cascade,
  role_id bigint not null references public.roles(id) on delete cascade,
  primary key (user_id, role_id)
);

create table if not exists public.role_permissions (
  role_id bigint not null references public.roles(id) on delete cascade,
  permission_id bigint not null references public.permissions(id) on delete cascade,
  primary key (role_id, permission_id)
);

create table if not exists public.sessions (
  token_hash text primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  expires_at bigint not null,
  created_at bigint not null
);
create index if not exists sessions_expiry_idx on public.sessions (expires_at);

create table if not exists public.user_invitations (
  user_id bigint primary key references public.users(id) on delete cascade,
  token_hash text not null unique,
  expires_at bigint not null,
  created_at bigint not null
);

create table if not exists public.app_state (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.app_meta (
  key text primary key,
  value text not null
);

insert into public.app_meta (key, value) values ('state_revision', '0')
on conflict (key) do nothing;

insert into public.roles (name) values
  ('Super Admin'), ('Admin'), ('Magasinier'), ('Consultation')
on conflict (name) do nothing;

insert into public.permissions (section, action)
select section, action
from unnest(array['products','stock','purchases','sales','suppliers','customers','reports','users']) as s(section)
cross join unnest(array['view','create','update','delete']) as a(action)
on conflict (section, action) do nothing;

-- Default role permissions, matching the local application's preset rules.
insert into public.role_permissions (role_id, permission_id)
select r.id, p.id
from public.roles r
cross join public.permissions p
where r.name = 'Super Admin'
   or (r.name = 'Admin' and p.action <> 'delete')
   or (r.name = 'Consultation' and p.action = 'view')
   or (r.name = 'Magasinier' and (
        (p.section in ('products','stock') and p.action in ('view','create','update'))
        or (p.section = 'purchases' and p.action = 'view')
        or (p.section = 'sales' and p.action in ('view','create','update'))
   ))
on conflict (role_id, permission_id) do nothing;

-- These tables are accessed only by the private Windows API connection.
-- Browser-facing Supabase API roles get no direct access to app data.
revoke all on public.users, public.roles, public.permissions, public.user_roles,
  public.role_permissions, public.sessions, public.user_invitations,
  public.app_state, public.app_meta from anon, authenticated;
grant all on public.users, public.roles, public.permissions, public.user_roles,
  public.role_permissions, public.sessions, public.user_invitations,
  public.app_state, public.app_meta to service_role;

