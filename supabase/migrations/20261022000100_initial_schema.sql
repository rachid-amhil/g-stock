-- Optimistic, atomic writes for the inventory collections.
create or replace function public.apply_app_state(p_state jsonb, p_expected_revision bigint)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
  current_revision bigint;
  next_revision bigint;
  state_key text;
begin
  select value::bigint into current_revision from public.app_meta where key='state_revision' for update;
  if current_revision is null then raise exception 'Missing state revision'; end if;
  if current_revision <> p_expected_revision then
    raise exception using errcode='40001', message='Stock data changed in another session. Reload before saving.';
  end if;
  for state_key in select jsonb_object_keys(p_state) loop
    if state_key not in ('inventory','movements','loans','office') then
      raise exception 'Invalid collection: %', state_key;
    end if;
    if jsonb_typeof(p_state->state_key) <> 'array' then raise exception 'Invalid collection: %', state_key; end if;
    insert into public.app_state(key,value,updated_at) values(state_key,p_state->state_key,now())
    on conflict(key) do update set value=excluded.value,updated_at=now();
  end loop;
  next_revision := current_revision + 1;
  update public.app_meta set value=next_revision::text where key='state_revision';
  return next_revision;
end;
$$;

create or replace function public.set_role_permissions(p_role_id bigint, p_permissions jsonb)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
  permission_row jsonb;
begin
  if not exists(select 1 from public.roles where id=p_role_id and name <> 'Super Admin') then
    raise exception 'Role not found or immutable';
  end if;
  delete from public.role_permissions where role_id=p_role_id;
  for permission_row in select value from jsonb_array_elements(p_permissions) loop
    insert into public.role_permissions(role_id,permission_id)
    select p_role_id,id from public.permissions
    where section=permission_row->>'section' and action=permission_row->>'action';
    if not found then raise exception 'Unknown permission'; end if;
  end loop;
  return true;
end;
$$;

create or replace function public.set_user_roles(p_user_id bigint, p_role_ids bigint[])
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if not exists(select 1 from public.users where id=p_user_id) then raise exception 'User not found'; end if;
  if coalesce(array_length(p_role_ids,1),0)=0 then raise exception 'At least one role is required'; end if;
  if (select count(distinct id) from public.roles where id=any(p_role_ids)) <> (select count(distinct x) from unnest(p_role_ids) as x) then
    raise exception 'Unknown role';
  end if;
  delete from public.user_roles where user_id=p_user_id;
  insert into public.user_roles(user_id,role_id) select p_user_id,id from public.roles where id=any(p_role_ids);
  return true;
end;
$$;

create or replace function public.activate_invitation(
  p_token_hash text, p_password_hash text, p_password_salt text,
  p_session_token_hash text, p_expires_at bigint, p_now bigint
)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
  target_user_id bigint;
begin
  select user_id into target_user_id from public.user_invitations
  where token_hash=p_token_hash and expires_at>p_now for update;
  if target_user_id is null then return null; end if;
  update public.users set password_hash=p_password_hash,password_salt=p_password_salt,
    active=true,last_login=now() where id=target_user_id;
  delete from public.user_invitations where user_id=target_user_id;
  insert into public.sessions(token_hash,user_id,expires_at,created_at)
    values(p_session_token_hash,target_user_id,p_expires_at,p_now);
  return target_user_id;
end;
$$;

